import { useCallback } from "react";
import { useLocation, useNavigate } from "react-router-dom";

/**
 * Кнопка «назад» на внутреннем экране.
 *
 * Правило: если в истории есть куда возвращаться — возвращаемся по ней, и
 * только на «холодном» входе (прямая ссылка, восстановление PWA с последнего
 * адреса) уходим по запасному адресу. Браузерной кнопки «назад» в
 * standalone-режиме нет, поэтому эта — единственная, и вести себя как история
 * она обязана буквально.
 *
 * Почему не просто navigate(fallback). Это ПУШ новой записи, и она встаёт
 * поверх той, из которой пользователь пришёл. Экран периода уходит назад через
 * navigate(-1), то есть попадает обратно на экспорт, чья «назад» снова пушит
 * период, — экраны начинают меняться местами до бесконечности, и выйти из
 * пары нельзя вовсе. Ровно это и происходило на паре «период ↔ экспорт» и
 * «период ↔ прошлые периоды».
 *
 * location.key === "default" означает, что запись в истории одна — эта. Тогда
 * возвращаться некуда и navigate(-1) просто ничего не сделает: экран замрёт.
 *
 * Экраны типов дня и праздников этой функцией намеренно НЕ пользуются: их
 * return= указывает на «/?day=2026-08-10», а в истории лежит просто «/» —
 * шаг назад по истории вернул бы пользователя на календарь без открытого дня,
 * ради которого он туда и уходил. Там пуш осознанный.
 */
export function useBackTo(fallback: string): () => void {
  const navigate = useNavigate();
  const location = useLocation();

  return useCallback(() => {
    if (location.key === "default") navigate(fallback);
    else navigate(-1);
  }, [navigate, location.key, fallback]);
}
