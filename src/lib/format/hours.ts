/**
 * Часы на экране — не больше двух знаков после запятой, без хвостовых нулей.
 *
 * В базе длительность, выведенная из времён (раздел 6.1), лежит НЕокруглённой:
 * 7ч20м это 440/60 = 7.333333333333333, и округлить её до сотых раньше
 * умножения на ставку значит потерять 10 грошей на смене — раздел 6.4
 * округляет один раз и только итоговую сумму за день. Но показывать человеку
 * «7.333333333333333ч» в поле шириной 80px нельзя, а инвариант 20 прямо
 * разрешает расхождение в обратную сторону: округлённое значение показывается,
 * но никогда не записывается обратно вместо исходного.
 */
export function formatHours(value: number): string {
  if (!Number.isFinite(value)) return String(value);
  // Number() убирает хвостовые нули: 7.50 → "7.5", 8.00 → "8".
  return String(Number(value.toFixed(2)));
}
