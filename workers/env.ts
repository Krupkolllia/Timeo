import type { Fetcher } from "./runtime";

/**
 * Переменные окружения воркера. Все до одной — секреты/переменные Cloudflare
 * (`wrangler secret put`), ни одна не лежит в репозитории (CLAUDE.md).
 *
 * Это НЕ те же значения, что `VITE_SUPABASE_*`: те Vite вшивает в бандл на
 * сборке и они живут в build-окружении Workers Builds. Воркеру нужны свои,
 * рантаймовые — build-переменная до рантайма не доезжает.
 *
 * Каждое поле необязательно намеренно. Сборка без ключей обязана работать
 * целиком (инвариант 39): воркер тогда отдаёт статику как раньше, а cron
 * честно ничего не делает, вместо того чтобы падать.
 */
export interface Env {
  /** Привязка статики: этот же воркер хостит собранное приложение. */
  ASSETS: Fetcher;

  /** Адрес проекта Supabase, например https://xxxx.supabase.co */
  SUPABASE_URL?: string;
  /** anon-ключ. Его хватает keep-alive: строк он не читает вовсе. */
  SUPABASE_ANON_KEY?: string;
}
